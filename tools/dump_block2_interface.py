#!/usr/bin/env python3
"""Dumps public signatures and dataclass fields of Block 2 modules using inspect.

Output is written to delivery-2-block2/INTERFACE-DUMP.txt.
Adheres strictly to machine-generation rule: zero hand-typed signatures or fields.
"""
from __future__ import annotations

import dataclasses
import inspect
from pathlib import Path
import sys
from typing import Any, List

repo_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(repo_root / "src"))
sys.path.insert(0, str(repo_root / "10-CONFORMANCE"))
sys.path.insert(0, str(repo_root / "20-RUNTIME"))

import sclass.product.gate as gate_mod
import sclass.product.artifacts as artifacts_mod
import sclass.product.trust_model as trust_mod
import sclass.product.gate_evaluator as gate_eval_mod
import sclass.product.metrics as metrics_mod
import sclass.product.performance_claims as perf_claims_mod
import sclass.product.check_registry as registry_mod
import sclass.product.gate_cache as cache_mod
try:
    import tools.fixture_runner as fixture_runner_mod
    fixture_bindings_mod = fixture_runner_mod
except ImportError:
    fixture_runner_mod = None
    fixture_bindings_mod = None


def dump_object(obj: Any, name: str, lines: List[str]) -> None:
    lines.append(f"--- {name} ---")
    if inspect.isfunction(obj):
        lines.append(f"Function: {name}{inspect.signature(obj)}")
        if obj.__doc__:
            lines.append(f"Docstring: {obj.__doc__.strip().splitlines()[0]}")
    elif inspect.isclass(obj):
        if dataclasses.is_dataclass(obj):
            lines.append(f"Dataclass: {name}")
            lines.append("Fields:")
            for f in dataclasses.fields(obj):
                parts = [f"  - {f.name}: {f.type}"]
                if f.default is not dataclasses.MISSING:
                    parts.append(f" = {f.default!r}")
                elif f.default_factory is not dataclasses.MISSING:
                    parts.append(" (factory)")
                lines.append("".join(parts))
        else:
            lines.append(f"Class: {name}")
            try:
                lines.append(f"Constructor: {inspect.signature(obj.__init__)}")
            except (ValueError, TypeError):
                pass
        methods = [
            (m_name, m_val)
            for m_name, m_val in inspect.getmembers(obj, predicate=inspect.isfunction)
            if not m_name.startswith("_")
        ]
        if methods:
            lines.append("Public Methods:")
            for m_name, m_val in methods:
                try:
                    lines.append(f"  - {m_name}{inspect.signature(m_val)}")
                except (ValueError, TypeError):
                    lines.append(f"  - {m_name}(...)")
    else:
        lines.append(f"Constant/Value: {name} = {obj!r}")
    lines.append("")


def main() -> int:
    output_lines: List[str] = [
        "================================================================================",
        "S-CLASS BLOCK 2 PUBLIC INTERFACES & DATACLASS DUMP (INSPECT-GENERATED)",
        "================================================================================",
        "Generated by: tools/dump_block2_interface.py",
        f"Python interpreter: {sys.version}",
        "",
    ]

    modules_to_dump = [
        ("sclass.product.gate", [
            ("GateOutput", gate_mod.GateOutput),
            ("GateState", gate_mod.GateState),
        ]),
        ("sclass.product.artifacts", [
            ("QUALIFIED_EVALUATOR_BOUNDARY", artifacts_mod.QUALIFIED_EVALUATOR_BOUNDARY),
            ("evaluate_f1_representation", artifacts_mod.evaluate_f1_representation),
        ]),
        ("sclass.product.trust_model", [
            ("evaluate_f3_trust", trust_mod.evaluate_f3_trust),
            ("ConfirmationEventSource", trust_mod.ConfirmationEventSource),
            ("HostAttestationSource", trust_mod.HostAttestationSource),
            ("InMemoryConfirmationEventSource", trust_mod.InMemoryConfirmationEventSource),
            ("InMemoryHostAttestationSource", trust_mod.InMemoryHostAttestationSource),
        ]),
        ("sclass.product.gate_evaluator", [
            ("QUALIFIED_EVALUATOR_BOUNDARY", gate_eval_mod.QUALIFIED_EVALUATOR_BOUNDARY),
            ("F5Result", gate_eval_mod.F5Result),
            ("FailureEntry", gate_eval_mod.FailureEntry),
            ("evaluate_f5_gate", gate_eval_mod.evaluate_f5_gate),
        ]),
        ("sclass.product.metrics", [
            ("QUALIFIED_EVALUATOR_BOUNDARY", metrics_mod.QUALIFIED_EVALUATOR_BOUNDARY),
            ("ProductMetricEnvelope", metrics_mod.ProductMetricEnvelope),
            ("evaluate_f9_metric", metrics_mod.evaluate_f9_metric),
        ]),
        ("sclass.product.performance_claims", [
            ("QUALIFIED_EVALUATOR_BOUNDARY", perf_claims_mod.QUALIFIED_EVALUATOR_BOUNDARY),
            ("evaluate_performance_claim", perf_claims_mod.evaluate_performance_claim),
        ]),
        ("sclass.product.check_registry", [
            ("QUALIFIED_EVALUATOR_BOUNDARY", registry_mod.QUALIFIED_EVALUATOR_BOUNDARY),
            ("CheckRecord", registry_mod.CheckRecord),
            ("compute_check_id", registry_mod.compute_check_id),
            ("get_check_record", registry_mod.get_check_record),
        ]),
        ("sclass.product.gate_cache", [
            ("QUALIFIED_EVALUATOR_BOUNDARY", cache_mod.QUALIFIED_EVALUATOR_BOUNDARY),
            ("GateCache", cache_mod.GateCache),
            ("compute_gate_cache_key", cache_mod.compute_gate_cache_key),
        ]),
        ("sclass.product.fixture_runner", [
            ("QUALIFIED_EVALUATOR_BOUNDARY", fixture_runner_mod.QUALIFIED_EVALUATOR_BOUNDARY),
            ("FixtureRunner", fixture_runner_mod.FixtureRunner),
            ("FixtureRecord", fixture_runner_mod.FixtureRecord),
            ("FixtureExecutionResult", fixture_runner_mod.FixtureExecutionResult),
        ]),
        ("sclass.product.fixture_bindings", [
            ("FixtureBinding", fixture_bindings_mod.FixtureBinding),
            ("execute_binding", fixture_bindings_mod.execute_binding),
        ]),
    ]

    for mod_name, items in modules_to_dump:
        output_lines.append(f"MODULE: {mod_name}")
        output_lines.append("=" * len(f"MODULE: {mod_name}"))
        for item_name, item_obj in items:
            dump_object(item_obj, item_name, output_lines)

    out_file = repo_root / "delivery-2-block2" / "INTERFACE-DUMP.txt"
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text("\n".join(output_lines) + "\n", encoding="utf-8")
    print(f"Interface dump successfully written to {out_file} ({len(output_lines)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
