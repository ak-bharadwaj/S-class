"""Generate src/sclass/product/registry_table.py from product/MUST-ALLOCATION-V3.csv and src/sclass/product/*.py."""
from __future__ import annotations

import ast
import csv
import hashlib
import pathlib
import re
from typing import Any, Dict, List, Tuple

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
V3_CSV = REPO_ROOT / "product/MUST-ALLOCATION-V3.csv"
PRODUCT_DIR = REPO_ROOT / "src/sclass/product"
OUT_PATH = PRODUCT_DIR / "registry_table.py"


def sha256_file(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def discover_evaluators(product_dir: pathlib.Path) -> Dict[str, Dict[str, Any]]:
    """Scan src/sclass/product/*.py for evaluate_pd_* functions."""
    found: Dict[str, Dict[str, Any]] = {}
    for p in sorted(product_dir.glob("*.py")):
        if p.name in {"registry.py", "registry_table.py", "__init__.py"}:
            continue
        tree = ast.parse(p.read_text(encoding="utf-8"))
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name.startswith("evaluate_"):
                m = re.search(r"evaluate_(?:pd_)?(ch\d+_\d+|f\d+_\d+)", node.name)
                if not m:
                    continue
                mid = "PD-" + m.group(1).upper().replace("_", "-")
                pos = [a.arg for a in node.args.posonlyargs + node.args.args]
                kw = [a.arg for a in node.args.kwonlyargs]
                all_params = tuple(pos + kw)
                # Prefer non-adapter direct module if both exist (adapters only cover the 54 without direct)
                if mid in found and p.name == "registry_adapters.py":
                    continue
                found[mid] = {
                    "module": f"sclass.product.{p.stem}",
                    "function_name": node.name,
                    "line": node.lineno,
                    "param_names": all_params,
                    "pos_names": tuple(pos),
                    "kw_names": tuple(kw),
                    "single_dict_param": len(pos) >= 1 and pos[0] in ("evidence", "payload") and all(p in ("authority", "caller_authority") for p in pos[1:]),
                }
    return found


def render_registry_table(
    v3_csv: pathlib.Path = V3_CSV,
    product_dir: pathlib.Path = PRODUCT_DIR,
) -> str:
    v3_sha = sha256_file(v3_csv)
    gen_sha = sha256_file(pathlib.Path(__file__).resolve())
    evaluators = discover_evaluators(product_dir)

    rows: List[Dict[str, Any]] = []
    with open(v3_csv, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["class"] == "RETIRED":
                continue
            mid = r["must_id"]
            ev = evaluators.get(mid)
            if ev is None:
                raise RuntimeError(f"Missing evaluator function for active MUST {mid}")
            rows.append(
                {
                    "must_id": mid,
                    "class_kind": r["class"],
                    "plane": r["plane"],
                    "block": r["block"],
                    "wi": r["wi"],
                    "needs_engine": r["needs_engine"].startswith("Y"),
                    "module": ev["module"],
                    "function_name": ev["function_name"],
                    "line": ev["line"],
                    "param_names": ev["param_names"],
                    "pos_names": ev["pos_names"],
                    "kw_names": ev["kw_names"],
                    "single_dict_param": ev["single_dict_param"],
                    "status_in_registry": "IMPLEMENTED",
                }
            )
    rows.sort(key=lambda x: x["must_id"])
    assert len(rows) == 195, f"Expected 195 active MUSTs, got {len(rows)}"

    entry_lines = [f"    {row!r}," for row in rows]
    entries_block = "\n".join(entry_lines)

    return f'''"""Explicit generated registry table for all 195 active S-Class MUSTs.

GENERATED FILE - DO NOT EDIT BY HAND.
Generated by tools/generate_registry_table.py
  product/MUST-ALLOCATION-V3.csv sha256 = {v3_sha}
  tools/generate_registry_table.py sha256 = {gen_sha}
  active_entries = {len(rows)} (PD-CH4-013 RETIRED excluded)
"""
from __future__ import annotations

from typing import Any, Dict, Tuple

V3_CSV_SHA256 = "{v3_sha}"
GENERATOR_SHA256 = "{gen_sha}"

REGISTRY_TABLE_ROWS: Tuple[Dict[str, Any], ...] = (
{entries_block}
)
'''


def main() -> None:
    content = render_registry_table(V3_CSV, PRODUCT_DIR)
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"Wrote {OUT_PATH} (195 entries)")


if __name__ == "__main__":
    main()
