def verify_spot_runs():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    tasks_dir = os.path.join(base_dir, "tasks_h6_2")

    print("=== Executing Exploratory Spot Check Pytest Verification ===")
    results = []

    for run in SPOT_RUNS:
        tid = run["task_id"]
        baseline = run["baseline"]
        code = run["code"]
        tdir = os.path.join(tasks_dir, tid)

        with tempfile.TemporaryDirectory() as tmp:
            # Write target module
            with open(os.path.join(tmp, "target_module.py"), "w", encoding="utf-8") as f:
                f.write(code)

            # Copy tests
            tmp_tests = os.path.join(tmp, "tests")
            os.makedirs(tmp_tests, exist_ok=True)
            for tfile in ["test_oracle.py", "test_adversarial_invariants.py"]:
                src_path = os.path.join(tdir, "tests", tfile)
                if os.path.exists(src_path):
                    with open(src_path, "r", encoding="utf-8") as f_in:
                        with open(os.path.join(tmp_tests, tfile), "w", encoding="utf-8") as f_out:
                            f_out.write(f_in.read())

            # Run Layer 1 Pytest
            l1_cmd = [sys.executable, "-m", "pytest", "tests/test_oracle.py"]
            l1_res = subprocess.run(l1_cmd, cwd=tmp, capture_output=True, text=True)
            l1_passed = (l1_res.returncode == 0)

            # Run Layer 2 Pytest
            l2_cmd = [sys.executable, "-m", "pytest", "tests/test_adversarial_invariants.py"]
            l2_res = subprocess.run(l2_cmd, cwd=tmp, capture_output=True, text=True)
            l2_passed = (l2_res.returncode == 0)

            res_entry = {
                "task_id": tid,
                "baseline": baseline,
                "l1_result": "PASS" if l1_passed else "FAIL",
                "l2_result": "PASS" if l2_passed else "FAIL",
                "calls": run["calls"],
                "latency_sec": run["latency_sec"]
            }
            results.append(res_entry)
            print(f"Task {tid} ({baseline}): L1={res_entry['l1_result']} | L2={res_entry['l2_result']}")

    with open(os.path.join(base_dir, "spot_check_results.json"), "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)

if __name__ == "__main__":
    verify_spot_runs()
