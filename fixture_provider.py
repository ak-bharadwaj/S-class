"""
S-Class v6 Pluggable Fixture & Simulation Decoupling Provider (fixture_provider.py)

Decouples test simulation fixtures, synthetic starter templates, and mock evidence
generation from the authoritative FSM microkernel (runtime.py).

Enforces clean boundary separation:
- ProductionFixtureProvider: Strictly zero canned solutions or artificial starter code.
- HeadlessTestFixtureProvider: Pluggable deterministic fallback fixtures for headless CI test harnesses.
"""

from __future__ import annotations
import os
import sys
import logging
from abc import ABC, abstractmethod
from typing import Optional, List, Dict, Any
from datetime import datetime, timezone

logger = logging.getLogger("sclass_fixture_provider")


class BaseFixtureProvider(ABC):
    """Abstract interface for starter code and evidence fixture generation."""

    @abstractmethod
    def synthesize_starter_code(self, workspace_dir: str, goal: Optional[str] = None, domain: str = "algorithm") -> List[str]:
        """Synthesizes initial implementation files if appropriate for execution mode."""
        pass

    @abstractmethod
    def ensure_phase_evidence(self, current_phase: str, workspace_dir: str) -> None:
        """Ensures necessary evidence artifacts exist for phase gates."""
        pass


class ProductionFixtureProvider(BaseFixtureProvider):
    """Production provider: Never injects canned code or artificial starter files."""

    def synthesize_starter_code(self, workspace_dir: str, goal: Optional[str] = None, domain: str = "algorithm") -> List[str]:
        # In production mode, live coding agents are expected to write code. No stubs injected.
        return []

    def ensure_phase_evidence(self, current_phase: str, workspace_dir: str) -> None:
        # In production mode, evidence must be produced organically by agents or tools.
        pass


class HeadlessTestFixtureProvider(BaseFixtureProvider):
    """Headless test provider: Provides deterministic fixtures for headless CI simulation runs."""

