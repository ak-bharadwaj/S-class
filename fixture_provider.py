_CUSTOM_PROVIDER: Optional[BaseFixtureProvider] = None


def set_fixture_provider(provider: Optional[BaseFixtureProvider]) -> None:
    """Sets an explicit custom fixture provider instance."""
    global _CUSTOM_PROVIDER
    _CUSTOM_PROVIDER = provider


def reset_provider() -> None:
    """Resets global custom provider singleton for clean test isolation."""
    global _CUSTOM_PROVIDER
    _CUSTOM_PROVIDER = None


def get_fixture_provider() -> BaseFixtureProvider:
    """
    Returns authoritative fixture provider based on environment and configuration:
    - Defaults to HeadlessTestFixtureProvider when running under pytest / simulation.
    - Defaults to ProductionFixtureProvider in live production environments.
    """
    global _CUSTOM_PROVIDER
    if _CUSTOM_PROVIDER is not None:
        return _CUSTOM_PROVIDER

    exec_mode = os.getenv("SCLASS_EXECUTION_MODE", "").upper()
    is_pytest = "pytest" in sys.modules or os.getenv("PYTEST_CURRENT_TEST") is not None

    if exec_mode in ("TEST", "SIMULATION") or is_pytest:
        return HeadlessTestFixtureProvider()
    return ProductionFixtureProvider()
